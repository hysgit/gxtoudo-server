CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    nickname TEXT NOT NULL,
    intro TEXT NOT NULL DEFAULT '',
    avatar TEXT NOT NULL DEFAULT '',
    inactive BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    device TEXT NOT NULL,
    token_hash TEXT NOT NULL,
    expires BIGINT NOT NULL,
    UNIQUE (user_id, device)
);
CREATE TABLE IF NOT EXISTS reset_codes (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    token_hash TEXT NOT NULL,
    expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name TEXT NOT NULL,
    type BIGINT NOT NULL,
    intro TEXT NOT NULL DEFAULT '',
    notice TEXT NOT NULL DEFAULT '',
    icon TEXT NOT NULL DEFAULT '',
    total_size BIGINT NOT NULL DEFAULT 1,
    status BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS personal_team ON teams(user_id) WHERE type = 1;
CREATE TABLE IF NOT EXISTS members (
    team_id BIGINT NOT NULL REFERENCES teams(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    role BIGINT NOT NULL,
    PRIMARY KEY(team_id, user_id)
);
CREATE TABLE IF NOT EXISTS revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);
CREATE TABLE IF NOT EXISTS objects (
    team_id BIGINT NOT NULL REFERENCES teams(id),
    table_id BIGINT NOT NULL,
    uid TEXT NOT NULL,
    revision BIGINT NOT NULL,
    login_id BIGINT NOT NULL,
    edit_time BIGINT NOT NULL,
    mode BIGINT NOT NULL,
    data TEXT NOT NULL,
    PRIMARY KEY(team_id, table_id, uid)
);
CREATE INDEX IF NOT EXISTS object_sync ON objects(team_id, revision);
CREATE TABLE IF NOT EXISTS receipts (
    login_id BIGINT NOT NULL REFERENCES sessions(id),
    fingerprint TEXT NOT NULL,
    revision BIGINT NOT NULL,
    PRIMARY KEY(login_id, fingerprint)
);
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender BIGINT NOT NULL REFERENCES users(id),
    recipient BIGINT NOT NULL REFERENCES users(id),
    event BIGINT NOT NULL,
    content TEXT NOT NULL,
    created_at TEXT NOT NULL,
    seen BIGINT NOT NULL DEFAULT 0,
    removed BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS message_inbox ON messages(recipient, removed, id);
CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author BIGINT NOT NULL REFERENCES users(id),
    team_id BIGINT NOT NULL REFERENCES teams(id),
    task_id TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS comment_task ON comments(team_id, task_id, id);

CREATE TABLE IF NOT EXISTS media (
    id TEXT PRIMARY KEY,
    owner BIGINT NOT NULL REFERENCES users(id),
    team_id BIGINT NOT NULL REFERENCES teams(id),
    note_id TEXT NOT NULL,
    object_key TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('image','audio','file')),
    content_type TEXT NOT NULL,
    size BIGINT NOT NULL CHECK (size > 0),
    sha256 TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS media_note ON media(owner,team_id,note_id);
CREATE TABLE IF NOT EXISTS media_clients (
    owner BIGINT NOT NULL REFERENCES users(id),
    client_id TEXT NOT NULL,
    media_id TEXT NOT NULL REFERENCES media(id),
    PRIMARY KEY(owner,client_id)
);
ALTER TABLE media DROP CONSTRAINT IF EXISTS media_kind_check;
ALTER TABLE media ADD CONSTRAINT media_kind_check CHECK (kind IN ('image','audio','file'));
CREATE TABLE IF NOT EXISTS media_parents (
    media_id TEXT PRIMARY KEY REFERENCES media(id),
    parent_table BIGINT NOT NULL CHECK (parent_table IN (49,51,89))
);
ALTER TABLE media_parents DROP CONSTRAINT IF EXISTS media_parents_parent_table_check;
ALTER TABLE media_parents ADD CONSTRAINT media_parents_parent_table_check CHECK (parent_table IN (49,51,89));

CREATE TABLE IF NOT EXISTS push_devices (
    login_id BIGINT PRIMARY KEY REFERENCES sessions(id),
    provider TEXT NOT NULL CHECK (provider IN ('apns','apns_sandbox','fcm')),
    token TEXT NOT NULL,
    timezone TEXT NOT NULL,
    UNIQUE (provider, token)
);
CREATE TABLE IF NOT EXISTS push_deliveries (
    login_id BIGINT NOT NULL REFERENCES sessions(id),
    team_id BIGINT NOT NULL REFERENCES teams(id),
    task_id TEXT NOT NULL,
    occurrence BIGINT NOT NULL,
    remind_at BIGINT NOT NULL,
    retry_at BIGINT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 1,
    finished BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (login_id, team_id, task_id, occurrence, remind_at)
);
CREATE INDEX IF NOT EXISTS push_delivery_age ON push_deliveries(remind_at);
CREATE INDEX IF NOT EXISTS push_alert_owner ON objects(team_id, (data::jsonb->>'user_id'))
    WHERE table_id=77 AND mode<>3;
CREATE INDEX IF NOT EXISTS push_task_related ON objects(team_id, table_id, (data::jsonb->>'task_id'))
    WHERE table_id IN (76,78) AND mode<>3;

CREATE TABLE IF NOT EXISTS ai_turns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    thread TEXT NOT NULL,
    request_id TEXT NOT NULL,
    question TEXT NOT NULL,
    timezone TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'queued',
    answer TEXT NOT NULL DEFAULT '',
    refs TEXT NOT NULL DEFAULT '[]',
    error TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL,
    lease_until BIGINT NOT NULL DEFAULT 0,
    UNIQUE(user_id, request_id)
);
CREATE INDEX IF NOT EXISTS ai_turn_history ON ai_turns(user_id, thread, id);
CREATE INDEX IF NOT EXISTS ai_pending_turns ON ai_turns(id) WHERE state IN ('queued','running');
ALTER TABLE ai_turns ADD COLUMN IF NOT EXISTS image_key TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS price_collectors (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    token_hash TEXT NOT NULL UNIQUE,
    last_seen BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS price_watches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    platform TEXT NOT NULL CHECK (platform IN ('jd','taobao')),
    url TEXT NOT NULL,
    name TEXT NOT NULL,
    variant TEXT NOT NULL,
    quantity INTEGER NOT NULL,
    region TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'waiting',
    next_check BIGINT NOT NULL DEFAULT 0,
    lease TEXT NOT NULL DEFAULT '',
    lease_until BIGINT NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS price_watch_owner ON price_watches(user_id,id);
ALTER TABLE price_watches ADD COLUMN IF NOT EXISTS sku_id TEXT NOT NULL DEFAULT '';
ALTER TABLE price_watches ADD COLUMN IF NOT EXISTS last_checked BIGINT NOT NULL DEFAULT 0;
ALTER TABLE price_watches ADD COLUMN IF NOT EXISTS last_observation_lease TEXT NOT NULL DEFAULT '';
UPDATE price_watches SET next_check=EXTRACT(EPOCH FROM NOW())::bigint+600
WHERE NOT deleted AND next_check>EXTRACT(EPOCH FROM NOW())::bigint+600;
CREATE TABLE IF NOT EXISTS price_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    watch_id BIGINT NOT NULL REFERENCES price_watches(id),
    request_id TEXT NOT NULL,
    amount NUMERIC(20,4) NOT NULL,
    previous NUMERIC(20,4),
    details TEXT NOT NULL,
    observed_at BIGINT NOT NULL,
    UNIQUE(watch_id,request_id)
);
CREATE INDEX IF NOT EXISTS price_history ON price_observations(watch_id,id DESC);
ALTER TABLE price_observations ADD COLUMN IF NOT EXISTS basis TEXT NOT NULL DEFAULT 'payable_verified';
CREATE TABLE IF NOT EXISTS price_notifications (
    observation_id BIGINT NOT NULL REFERENCES price_observations(id),
    login_id BIGINT NOT NULL REFERENCES sessions(id),
    attempts INTEGER NOT NULL DEFAULT 1,
    retry_at BIGINT NOT NULL,
    finished BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY(observation_id,login_id)
);
